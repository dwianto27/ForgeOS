
-- ForgeOS: Initial database schema
-- Target: a NEW Supabase project
-- Does not migrate existing user data.

BEGIN;

-- 1. Projects
CREATE TABLE public.projects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    description text NOT NULL DEFAULT '',
    color text NOT NULL DEFAULT 'violet',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    user_id uuid NOT NULL
        REFERENCES auth.users(id) ON DELETE CASCADE
);

-- 2. Tasks
CREATE TABLE public.tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL
        REFERENCES public.projects(id) ON DELETE CASCADE,
    title text NOT NULL,
    is_completed boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    status text NOT NULL DEFAULT 'todo',
    description text NOT NULL DEFAULT '',
    priority text NOT NULL DEFAULT 'medium',
    day integer NOT NULL DEFAULT 1,

    CONSTRAINT tasks_status_check
        CHECK (status IN ('todo', 'in_progress', 'done')),

    CONSTRAINT tasks_priority_check
        CHECK (priority IN ('low', 'medium', 'high'))
);

-- 3. AI provider settings
CREATE TABLE public.ai_provider_settings (
    id uuid NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
    user_id uuid NOT NULL UNIQUE
        REFERENCES auth.users(id) ON DELETE CASCADE,
    provider_name text NOT NULL DEFAULT 'Custom',
    base_url text NOT NULL,
    model text NOT NULL,
    encrypted_api_key text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT ai_provider_settings_base_url_length
        CHECK (char_length(base_url) BETWEEN 1 AND 2048),

    CONSTRAINT ai_provider_settings_key_length
        CHECK (char_length(encrypted_api_key) BETWEEN 1 AND 4096),

    CONSTRAINT ai_provider_settings_model_length
        CHECK (char_length(model) BETWEEN 1 AND 200),

    CONSTRAINT ai_provider_settings_provider_length
        CHECK (char_length(provider_name) BETWEEN 1 AND 100)
);


-- Additional indexes from the original ForgeOS schema
CREATE INDEX projects_user_id_idx
    ON public.projects USING btree (user_id);

CREATE INDEX tasks_project_id_idx
    ON public.tasks USING btree (project_id);


-- 4. Enable Row Level Security
ALTER TABLE public.projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ai_provider_settings ENABLE ROW LEVEL SECURITY;

-- 5. Projects policies
CREATE POLICY projects_select_own
ON public.projects FOR SELECT TO authenticated
USING (auth.uid() = user_id);

CREATE POLICY projects_insert_own
ON public.projects FOR INSERT TO authenticated
WITH CHECK (auth.uid() = user_id);

CREATE POLICY projects_update_own
ON public.projects FOR UPDATE TO authenticated
USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);

CREATE POLICY projects_delete_own
ON public.projects FOR DELETE TO authenticated
USING (auth.uid() = user_id);

-- 6. Tasks policies
CREATE POLICY tasks_select_own_project
ON public.tasks FOR SELECT TO authenticated
USING (
    EXISTS (
        SELECT 1
        FROM public.projects p
        WHERE p.id = tasks.project_id
          AND p.user_id = auth.uid()
    )
);

CREATE POLICY tasks_insert_own_project
ON public.tasks FOR INSERT TO authenticated
WITH CHECK (
    EXISTS (
        SELECT 1
        FROM public.projects p
        WHERE p.id = tasks.project_id
          AND p.user_id = auth.uid()
    )
);

CREATE POLICY tasks_update_own_project
ON public.tasks FOR UPDATE TO authenticated
USING (
    EXISTS (
        SELECT 1
        FROM public.projects p
        WHERE p.id = tasks.project_id
          AND p.user_id = auth.uid()
    )
)
WITH CHECK (
    EXISTS (
        SELECT 1
        FROM public.projects p
        WHERE p.id = tasks.project_id
          AND p.user_id = auth.uid()
    )
);

CREATE POLICY tasks_delete_own_project
ON public.tasks FOR DELETE TO authenticated
USING (
    EXISTS (
        SELECT 1
        FROM public.projects p
        WHERE p.id = tasks.project_id
          AND p.user_id = auth.uid()
    )
);

-- 7. AI provider settings policies
CREATE POLICY "Users can read their own AI settings"
ON public.ai_provider_settings FOR SELECT TO authenticated
USING (user_id = auth.uid());

CREATE POLICY "Users can insert their own AI settings"
ON public.ai_provider_settings FOR INSERT TO authenticated
WITH CHECK (user_id = auth.uid());

CREATE POLICY "Users can update their own AI settings"
ON public.ai_provider_settings FOR UPDATE TO authenticated
USING (user_id = auth.uid())
WITH CHECK (user_id = auth.uid());

CREATE POLICY "Users can delete their own AI settings"
ON public.ai_provider_settings FOR DELETE TO authenticated
USING (user_id = auth.uid());

-- 8. Table privileges
GRANT SELECT, INSERT, UPDATE, DELETE
ON TABLE
    public.projects,
    public.tasks,
    public.ai_provider_settings
TO authenticated;

GRANT ALL PRIVILEGES
ON TABLE
    public.projects,
    public.tasks,
    public.ai_provider_settings
TO service_role;

COMMIT;
